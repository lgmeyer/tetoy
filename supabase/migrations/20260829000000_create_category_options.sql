create table if not exists public.category_options (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 80),
  direction text not null default 'debit' check (direction in ('debit', 'credit')),
  created_at timestamptz not null default now()
);

create unique index if not exists category_options_name_lower_idx
  on public.category_options (lower(name));

