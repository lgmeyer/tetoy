alter table public.category_options enable row level security;

drop policy if exists "Public can read category options" on public.category_options;
create policy "Public can read category options"
  on public.category_options
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can create category options" on public.category_options;
create policy "Public can create category options"
  on public.category_options
  for insert
  to anon, authenticated
  with check (true);

grant select, insert on table public.category_options to anon, authenticated;
grant usage, select on sequence public.category_options_id_seq to anon, authenticated;
